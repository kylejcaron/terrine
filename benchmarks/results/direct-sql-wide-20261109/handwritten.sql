WITH totals AS (
  SELECT u.unit_id AS unit,
    count(e.event_id) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '1 days') AS n1,
    count(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '1 days') AS nn1,
    sum(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '1 days') AS s1,
    count(e.event_id) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '2 days') AS n2,
    count(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '2 days') AS nn2,
    sum(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '2 days') AS s2,
    count(e.event_id) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '3 days') AS n3,
    count(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '3 days') AS nn3,
    sum(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '3 days') AS s3,
    count(e.event_id) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '4 days') AS n4,
    count(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '4 days') AS nn4,
    sum(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '4 days') AS s4,
    count(e.event_id) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '5 days') AS n5,
    count(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '5 days') AS nn5,
    sum(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '5 days') AS s5,
    count(e.event_id) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '6 days') AS n6,
    count(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '6 days') AS nn6,
    sum(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '6 days') AS s6,
    count(e.event_id) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '7 days') AS n7,
    count(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '7 days') AS nn7,
    sum(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '7 days') AS s7,
    count(e.event_id) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '8 days') AS n8,
    count(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '8 days') AS nn8,
    sum(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '8 days') AS s8,
    count(e.event_id) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '9 days') AS n9,
    count(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '9 days') AS nn9,
    sum(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '9 days') AS s9,
    count(e.event_id) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '10 days') AS n10,
    count(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '10 days') AS nn10,
    sum(e.value) FILTER (WHERE e.event_time >= TIMESTAMPTZ '2025-01-15 00:00:00+00' - INTERVAL '10 days') AS s10
  FROM users u LEFT JOIN events_native e ON e.unit_id = u.unit_id
    AND e.event_time >= TIMESTAMPTZ '2025-01-05 00:00:00+00'
    AND e.event_time < TIMESTAMPTZ '2025-01-15 00:00:00+00'
  GROUP BY u.unit_id
)
SELECT unit,
  TIMESTAMPTZ '2025-01-15 00:00:00+00' AS t0,
  n1::BIGINT AS events_1d,
  TRUE AS events_1d__complete,
  NULL::VARCHAR AS events_1d__reason,
  n2::BIGINT AS events_2d,
  TRUE AS events_2d__complete,
  NULL::VARCHAR AS events_2d__reason,
  n3::BIGINT AS events_3d,
  TRUE AS events_3d__complete,
  NULL::VARCHAR AS events_3d__reason,
  n4::BIGINT AS events_4d,
  TRUE AS events_4d__complete,
  NULL::VARCHAR AS events_4d__reason,
  n5::BIGINT AS events_5d,
  TRUE AS events_5d__complete,
  NULL::VARCHAR AS events_5d__reason,
  n6::BIGINT AS events_6d,
  TRUE AS events_6d__complete,
  NULL::VARCHAR AS events_6d__reason,
  n7::BIGINT AS events_7d,
  TRUE AS events_7d__complete,
  NULL::VARCHAR AS events_7d__reason,
  n8::BIGINT AS events_8d,
  TRUE AS events_8d__complete,
  NULL::VARCHAR AS events_8d__reason,
  n9::BIGINT AS events_9d,
  TRUE AS events_9d__complete,
  NULL::VARCHAR AS events_9d__reason,
  n10::BIGINT AS events_10d,
  TRUE AS events_10d__complete,
  NULL::VARCHAR AS events_10d__reason,
  CASE WHEN n1 = 0 THEN 0.0 ELSE s1 END AS total_1d,
  TRUE AS total_1d__complete,
  CASE WHEN n1 > 0 AND nn1 = 0 THEN 'all_values_null' END AS total_1d__reason,
  CASE WHEN n2 = 0 THEN 0.0 ELSE s2 END AS total_2d,
  TRUE AS total_2d__complete,
  CASE WHEN n2 > 0 AND nn2 = 0 THEN 'all_values_null' END AS total_2d__reason,
  CASE WHEN n3 = 0 THEN 0.0 ELSE s3 END AS total_3d,
  TRUE AS total_3d__complete,
  CASE WHEN n3 > 0 AND nn3 = 0 THEN 'all_values_null' END AS total_3d__reason,
  CASE WHEN n4 = 0 THEN 0.0 ELSE s4 END AS total_4d,
  TRUE AS total_4d__complete,
  CASE WHEN n4 > 0 AND nn4 = 0 THEN 'all_values_null' END AS total_4d__reason,
  CASE WHEN n5 = 0 THEN 0.0 ELSE s5 END AS total_5d,
  TRUE AS total_5d__complete,
  CASE WHEN n5 > 0 AND nn5 = 0 THEN 'all_values_null' END AS total_5d__reason,
  CASE WHEN n6 = 0 THEN 0.0 ELSE s6 END AS total_6d,
  TRUE AS total_6d__complete,
  CASE WHEN n6 > 0 AND nn6 = 0 THEN 'all_values_null' END AS total_6d__reason,
  CASE WHEN n7 = 0 THEN 0.0 ELSE s7 END AS total_7d,
  TRUE AS total_7d__complete,
  CASE WHEN n7 > 0 AND nn7 = 0 THEN 'all_values_null' END AS total_7d__reason,
  CASE WHEN n8 = 0 THEN 0.0 ELSE s8 END AS total_8d,
  TRUE AS total_8d__complete,
  CASE WHEN n8 > 0 AND nn8 = 0 THEN 'all_values_null' END AS total_8d__reason,
  CASE WHEN n9 = 0 THEN 0.0 ELSE s9 END AS total_9d,
  TRUE AS total_9d__complete,
  CASE WHEN n9 > 0 AND nn9 = 0 THEN 'all_values_null' END AS total_9d__reason,
  CASE WHEN n10 = 0 THEN 0.0 ELSE s10 END AS total_10d,
  TRUE AS total_10d__complete,
  CASE WHEN n10 > 0 AND nn10 = 0 THEN 'all_values_null' END AS total_10d__reason,
  s1 / NULLIF(nn1, 0) AS average_1d,
  TRUE AS average_1d__complete,
  CASE WHEN n1 = 0 THEN 'no_observations' WHEN nn1 = 0 THEN 'all_values_null' END AS average_1d__reason,
  s2 / NULLIF(nn2, 0) AS average_2d,
  TRUE AS average_2d__complete,
  CASE WHEN n2 = 0 THEN 'no_observations' WHEN nn2 = 0 THEN 'all_values_null' END AS average_2d__reason,
  s3 / NULLIF(nn3, 0) AS average_3d,
  TRUE AS average_3d__complete,
  CASE WHEN n3 = 0 THEN 'no_observations' WHEN nn3 = 0 THEN 'all_values_null' END AS average_3d__reason,
  s4 / NULLIF(nn4, 0) AS average_4d,
  TRUE AS average_4d__complete,
  CASE WHEN n4 = 0 THEN 'no_observations' WHEN nn4 = 0 THEN 'all_values_null' END AS average_4d__reason,
  s5 / NULLIF(nn5, 0) AS average_5d,
  TRUE AS average_5d__complete,
  CASE WHEN n5 = 0 THEN 'no_observations' WHEN nn5 = 0 THEN 'all_values_null' END AS average_5d__reason,
  s6 / NULLIF(nn6, 0) AS average_6d,
  TRUE AS average_6d__complete,
  CASE WHEN n6 = 0 THEN 'no_observations' WHEN nn6 = 0 THEN 'all_values_null' END AS average_6d__reason,
  s7 / NULLIF(nn7, 0) AS average_7d,
  TRUE AS average_7d__complete,
  CASE WHEN n7 = 0 THEN 'no_observations' WHEN nn7 = 0 THEN 'all_values_null' END AS average_7d__reason,
  s8 / NULLIF(nn8, 0) AS average_8d,
  TRUE AS average_8d__complete,
  CASE WHEN n8 = 0 THEN 'no_observations' WHEN nn8 = 0 THEN 'all_values_null' END AS average_8d__reason,
  s9 / NULLIF(nn9, 0) AS average_9d,
  TRUE AS average_9d__complete,
  CASE WHEN n9 = 0 THEN 'no_observations' WHEN nn9 = 0 THEN 'all_values_null' END AS average_9d__reason,
  s10 / NULLIF(nn10, 0) AS average_10d,
  TRUE AS average_10d__complete,
  CASE WHEN n10 = 0 THEN 'no_observations' WHEN nn10 = 0 THEN 'all_values_null' END AS average_10d__reason,
  s1 / NULLIF(n1, 0) AS per_event_1d,
  TRUE AS per_event_1d__complete,
  CASE WHEN n1 = 0 THEN 'zero_denominator' WHEN nn1 = 0 THEN 'all_values_null' END AS per_event_1d__reason,
  s2 / NULLIF(n2, 0) AS per_event_2d,
  TRUE AS per_event_2d__complete,
  CASE WHEN n2 = 0 THEN 'zero_denominator' WHEN nn2 = 0 THEN 'all_values_null' END AS per_event_2d__reason,
  s3 / NULLIF(n3, 0) AS per_event_3d,
  TRUE AS per_event_3d__complete,
  CASE WHEN n3 = 0 THEN 'zero_denominator' WHEN nn3 = 0 THEN 'all_values_null' END AS per_event_3d__reason,
  s4 / NULLIF(n4, 0) AS per_event_4d,
  TRUE AS per_event_4d__complete,
  CASE WHEN n4 = 0 THEN 'zero_denominator' WHEN nn4 = 0 THEN 'all_values_null' END AS per_event_4d__reason,
  s5 / NULLIF(n5, 0) AS per_event_5d,
  TRUE AS per_event_5d__complete,
  CASE WHEN n5 = 0 THEN 'zero_denominator' WHEN nn5 = 0 THEN 'all_values_null' END AS per_event_5d__reason,
  s6 / NULLIF(n6, 0) AS per_event_6d,
  TRUE AS per_event_6d__complete,
  CASE WHEN n6 = 0 THEN 'zero_denominator' WHEN nn6 = 0 THEN 'all_values_null' END AS per_event_6d__reason,
  s7 / NULLIF(n7, 0) AS per_event_7d,
  TRUE AS per_event_7d__complete,
  CASE WHEN n7 = 0 THEN 'zero_denominator' WHEN nn7 = 0 THEN 'all_values_null' END AS per_event_7d__reason,
  s8 / NULLIF(n8, 0) AS per_event_8d,
  TRUE AS per_event_8d__complete,
  CASE WHEN n8 = 0 THEN 'zero_denominator' WHEN nn8 = 0 THEN 'all_values_null' END AS per_event_8d__reason,
  s9 / NULLIF(n9, 0) AS per_event_9d,
  TRUE AS per_event_9d__complete,
  CASE WHEN n9 = 0 THEN 'zero_denominator' WHEN nn9 = 0 THEN 'all_values_null' END AS per_event_9d__reason,
  s10 / NULLIF(n10, 0) AS per_event_10d,
  TRUE AS per_event_10d__complete,
  CASE WHEN n10 = 0 THEN 'zero_denominator' WHEN nn10 = 0 THEN 'all_values_null' END AS per_event_10d__reason,
  CASE WHEN n1 > 0 THEN 1.0 ELSE 0.0 END AS active_1d,
  TRUE AS active_1d__complete,
  NULL::VARCHAR AS active_1d__reason,
  CASE WHEN n2 > 0 THEN 1.0 ELSE 0.0 END AS active_2d,
  TRUE AS active_2d__complete,
  NULL::VARCHAR AS active_2d__reason,
  CASE WHEN n3 > 0 THEN 1.0 ELSE 0.0 END AS active_3d,
  TRUE AS active_3d__complete,
  NULL::VARCHAR AS active_3d__reason,
  CASE WHEN n4 > 0 THEN 1.0 ELSE 0.0 END AS active_4d,
  TRUE AS active_4d__complete,
  NULL::VARCHAR AS active_4d__reason,
  CASE WHEN n5 > 0 THEN 1.0 ELSE 0.0 END AS active_5d,
  TRUE AS active_5d__complete,
  NULL::VARCHAR AS active_5d__reason,
  CASE WHEN n6 > 0 THEN 1.0 ELSE 0.0 END AS active_6d,
  TRUE AS active_6d__complete,
  NULL::VARCHAR AS active_6d__reason,
  CASE WHEN n7 > 0 THEN 1.0 ELSE 0.0 END AS active_7d,
  TRUE AS active_7d__complete,
  NULL::VARCHAR AS active_7d__reason,
  CASE WHEN n8 > 0 THEN 1.0 ELSE 0.0 END AS active_8d,
  TRUE AS active_8d__complete,
  NULL::VARCHAR AS active_8d__reason,
  CASE WHEN n9 > 0 THEN 1.0 ELSE 0.0 END AS active_9d,
  TRUE AS active_9d__complete,
  NULL::VARCHAR AS active_9d__reason,
  CASE WHEN n10 > 0 THEN 1.0 ELSE 0.0 END AS active_10d,
  TRUE AS active_10d__complete,
  NULL::VARCHAR AS active_10d__reason
FROM totals ORDER BY unit, t0
